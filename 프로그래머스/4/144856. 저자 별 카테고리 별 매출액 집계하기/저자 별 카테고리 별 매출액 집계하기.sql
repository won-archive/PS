SELECT B.AUTHOR_ID, A.AUTHOR_NAME, B.CATEGORY, SUM(B.PRICE * S.SALES) AS TOTAL_SALES
FROM BOOK B
JOIN AUTHOR A ON A.AUTHOR_ID = B.AUTHOR_ID
JOIN BOOK_SALES S ON S.BOOK_ID = B.BOOK_ID
WHERE S.SALES_DATE LIKE '2022-01%'  -- 2022년 1월
GROUP BY A.AUTHOR_ID, B.CATEGORY  -- 저자 별, 카테고리 별
ORDER BY B.AUTHOR_ID, B.CATEGORY DESC   -- 저자 ID 오름차순, 카테고리 내림차순